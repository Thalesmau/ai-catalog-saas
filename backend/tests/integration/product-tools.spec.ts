import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { z } from 'zod';

import { IAgentTool } from '@application/ai/AgentTool';
import { createProductTools } from '@application/ai/tools/productTools';
import { MongoDbClient } from '@infra/clients/MongoDbClient';
import { ProductRepository } from '@infra/database/repositories/ProductRepository';
import { Registry } from '@kernel/di/Registry';

import { connectTestDatabase, disconnectTestDatabase } from '../helpers/testApp';

const COMPANY_A = '64b000000000000000000001';
const COMPANY_B = '64b000000000000000000002';

describe('agent product tools', () => {
  let mongoDbClient: MongoDbClient;
  let productRepository: ProductRepository;
  let productOfB: { id: string };

  const toolOf = (companyId: string, name: string) =>
    createProductTools({ companyId, productRepository }).find(tool => tool.name === name) as IAgentTool;

  const run = (tool: IAgentTool, input: unknown) => tool.run(tool.inputSchema.parse(input)) as Promise<any>;

  beforeAll(async () => {
    mongoDbClient = await connectTestDatabase();
    productRepository = Registry.getInstance().resolve(ProductRepository);

    await productRepository.create(COMPANY_A, {
      name: 'Fone Bluetooth', description: 'Fone sem fio.', priceInCents: 19990, category: 'Áudio', imageUrl: null,
    });
    await productRepository.create(COMPANY_A, {
      name: 'Fone com fio', description: 'Fone P2.', priceInCents: 4990, category: 'Áudio', imageUrl: null,
    });
    productOfB = await productRepository.create(COMPANY_B, {
      name: 'Fone Premium B', description: 'Produto da empresa B.', priceInCents: 99990, category: 'Áudio', imageUrl: null,
    });
  });

  afterAll(async () => {
    await disconnectTestDatabase(mongoDbClient);
  });

  it('search_products only returns products of the bound company', async () => {
    const result = await run(toolOf(COMPANY_A, 'search_products'), { query: 'fone' });

    expect(result.total).toBe(2);
    expect(result.products.map((p: { name: string }) => p.name)).not.toContain('Fone Premium B');
  });

  it('converts prices in reais to cents and formats them in BRL', async () => {
    const result = await run(toolOf(COMPANY_A, 'search_products'), { maxPrice: 50, sortBy: 'price_asc' });

    expect(result.products).toHaveLength(1);
    expect(result.products[0]).toMatchObject({ name: 'Fone com fio', priceInCents: 4990 });
    expect(result.products[0].price).toMatch(/R\$\s?49,90/);
  });

  it('matches every search term ignoring accents and stopwords', async () => {
    const result = await run(toolOf(COMPANY_A, 'search_products'), { query: 'fone de AUDIO sem fio' });

    expect(result.products.map((p: { name: string }) => p.name)).toEqual(['Fone Bluetooth']);
    expect(result.note).toBeUndefined();
  });

  it('falls back to any term when no product has all of them, and tells the model', async () => {
    const result = await run(toolOf(COMPANY_A, 'search_products'), { query: 'fone de ouvido' });

    expect(result.total).toBe(2);
    expect(result.note).toMatch(/ao menos um/);
  });

  it('get_product_details cannot read a product of another company', async () => {
    const result = await run(toolOf(COMPANY_A, 'get_product_details'), { productId: productOfB.id });

    expect(result).toEqual({ error: 'Produto não encontrado.' });
  });

  it('list_categories summarizes only the bound company catalog', async () => {
    const result = await run(toolOf(COMPANY_A, 'list_categories'), {});

    expect(result.categories).toEqual([
      { category: 'Áudio', productCount: 2, priceRange: expect.stringMatching(/49,90 a .*199,90/) },
    ]);
  });

  it('exposes no companyId in the schemas sent to the model', () => {
    for (const tool of createProductTools({ companyId: COMPANY_A, productRepository })) {
      expect(JSON.stringify(z.toJSONSchema(tool.inputSchema))).not.toMatch(/company/i);
    }
  });

  it('ignores a companyId injected in the tool arguments', async () => {
    const result = await run(toolOf(COMPANY_A, 'search_products'), { query: 'Premium', companyId: COMPANY_B });

    expect(result.total).toBe(0);
  });

  it('rejects invalid arguments generated by the model', () => {
    const search = toolOf(COMPANY_A, 'search_products');

    expect(search.inputSchema.safeParse({ limit: 50 }).success).toBe(false);
    expect(search.inputSchema.safeParse({ sortBy: 'random' }).success).toBe(false);
  });
});
